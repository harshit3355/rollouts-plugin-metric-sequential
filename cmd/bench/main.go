// Command bench regenerates reports/benchmark.json and reports/benchmark.md
// from seeded simulations. The output contains no timestamps, so the same
// seed and Go version reproduce the files byte for byte.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/harshit3355/rollouts-plugin-metric-sequential/internal/sim"
)

type report struct {
	GeneratedBy string       `json:"generatedBy"`
	GoVersion   string       `json:"goVersion"`
	Reps        int          `json:"repsPerScenario"`
	Seed        uint64       `json:"seed"`
	Alpha       float64      `json:"alpha"`
	Margin      float64      `json:"margin"`
	Weights     []float64    `json:"canaryWeights"`
	StepWindows int          `json:"windowsPerStep"`
	Results     []sim.Result `json:"results"`
}

func main() {
	reps := flag.Int("reps", 2000, "simulated rollouts per scenario")
	seed := flag.Uint64("seed", 1, "base seed")
	out := flag.String("out", "reports", "output directory")
	flag.Parse()

	var scenarios []sim.Scenario
	for _, base := range []float64{0.001, 0.01, 0.05, 0.2} {
		for _, traffic := range []int{500, 5000} {
			for _, eff := range []float64{1, 1.1, 1.25, 1.5, 2, 3, 5} {
				if base*eff <= 0.95 {
					scenarios = append(scenarios, sim.Scenario{BaseRate: base, Effect: eff, Traffic: traffic})
				}
			}
		}
	}
	rep := report{
		GeneratedBy: "go run ./cmd/bench -reps " + fmt.Sprint(*reps) + " -seed " + fmt.Sprint(*seed),
		GoVersion:   runtime.Version(), Reps: *reps, Seed: *seed,
		Alpha: sim.Alpha, Margin: sim.Margin, Weights: sim.Weights, StepWindows: sim.StepWindows,
	}
	for i, s := range scenarios {
		rep.Results = append(rep.Results, sim.Run(s, *reps, *seed+uint64(i))...)
	}

	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatal(err)
	}
	js, err := json.MarshalIndent(rep, "", "  ")
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "benchmark.json"), append(js, '\n'), 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "benchmark.md"), []byte(markdown(rep)), 0o644); err != nil {
		log.Fatal(err)
	}
}

func pct(v float64) string { return fmt.Sprintf("%.1f%%", 100*v) }

func methods(rep report) []string {
	var names []string
	seen := map[string]bool{}
	for _, r := range rep.Results {
		if !seen[r.Method] {
			seen[r.Method] = true
			names = append(names, r.Method)
		}
	}
	return names
}

func find(rep report, base float64, traffic int, eff float64, method string) (sim.Result, bool) {
	for _, r := range rep.Results {
		if r.Scenario.BaseRate == base && r.Scenario.Traffic == traffic && r.Scenario.Effect == eff && r.Method == method {
			return r, true
		}
	}
	return sim.Result{}, false
}

func markdown(rep report) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Benchmark: anytime-valid canary analysis vs common rollback rules\n\n")
	w("Generated by `%s` with %s. All traffic is **synthetic**: per-request Bernoulli bad events, ", rep.GeneratedBy, rep.GoVersion)
	w("%d simulated rollouts per scenario. Every method sees the same streams.\n\n", rep.Reps)
	w("Rollout: canary weight %v, %d analysis windows per step (%d looks). alpha = %g, margin = %g ", rep.Weights, rep.StepWindows, len(rep.Weights)*rep.StepWindows, rep.Alpha, rep.Margin)
	w("(a canary up to %g%% worse than baseline counts as harmless).\n\n", 100*rep.Margin)

	w("## False rollbacks of harmless canaries\n\n")
	w("Scenarios with effect <= 1 + margin (canary rate / baseline rate of 1.0 or 1.1), across every base rate and traffic level.\n\n")
	w("| Method | Worst scenario | Mean |\n|---|---|---|\n")
	for _, m := range methods(rep) {
		var worst, sum float64
		var n int
		for _, r := range rep.Results {
			if r.Method == m && r.Scenario.Effect <= 1+rep.Margin {
				worst = max(worst, r.RollbackRate)
				sum += r.RollbackRate
				n++
			}
		}
		w("| %s | %s | %s |\n", m, pct(worst), pct(sum/float64(n)))
	}

	for _, set := range []struct {
		base    float64
		traffic int
	}{{0.01, 5000}, {0.001, 500}} {
		w("\n## Detection: base rate %g, %d requests per window\n\n", set.base, set.traffic)
		w("Rollback rate / mean window of rollback (1-40) / expected extra bad events served by the canary before the decision.\n\n")
		w("| Method | 1.0x | 1.25x | 1.5x | 2x | 3x | 5x |\n|---|---|---|---|---|---|---|\n")
		for _, m := range methods(rep) {
			w("| %s ", m)
			for _, eff := range []float64{1, 1.25, 1.5, 2, 3, 5} {
				r, ok := find(rep, set.base, set.traffic, eff, m)
				if !ok {
					w("| - ")
					continue
				}
				w("| %s / %.1f / %.1f ", pct(r.RollbackRate), r.MeanDetectionLook, r.MeanExcessBad)
			}
			w("|\n")
		}
	}

	w("\n## All scenarios\n\n| Base rate | Requests/window | Effect | Method | Rollback rate | Mean window | Extra bad events |\n|---|---|---|---|---|---|---|\n")
	for _, r := range rep.Results {
		w("| %g | %d | %g | %s | %s | %.1f | %.1f |\n", r.Scenario.BaseRate, r.Scenario.Traffic, r.Scenario.Effect, r.Method, pct(r.RollbackRate), r.MeanDetectionLook, r.MeanExcessBad)
	}

	w("\n## What this result does not establish\n\n")
	w("- The traffic is simulated. Real bad events are bursty and correlated (retries, shared dependencies, a bad node); the test assumes independent events at a constant rate within each arm.\n")
	w("- The test models bad events as Poisson. With Bernoulli traffic the conditional distribution differs at high bad-event rates; the 0.2 base-rate rows measure how much that matters here, not in general.\n")
	w("- Prometheus counts are extrapolated by `increase()` and arrive with scrape delay; the simulation uses exact counts.\n")
	w("- The threshold rule's setting (2x the baseline rate, failureLimit 2) is one common choice, not the best possible threshold.\n")
	w("- Nothing here shows the plugin running in a cluster; see the end-to-end test for that.\n")
	return b.String()
}
